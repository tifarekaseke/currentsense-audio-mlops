"""Streamlit dashboard and operator UI for the CurrentSense MLOps demonstration."""
import os
import json
from pathlib import Path
import requests
import streamlit as st
import pandas as pd

API=os.getenv('API_URL','http://localhost:8000').rstrip('/')
ADMIN=os.getenv('ADMIN_TOKEN','')
st.set_page_config(page_title='CurrentSense | Motor Audio MLOps',page_icon='🎧',layout='wide')
st.title('🎧 CurrentSense MLOps')
st.caption('Industrial fan/motor condition screening | WAV audio | Cloud-ready prediction and retraining')

def get(path):
    r=requests.get(API+path,timeout=120)
    r.raise_for_status()
    return r.json()

def post(path,**kwargs):
    r=requests.post(API+path,headers={'X-Admin-Token':ADMIN},timeout=90,**kwargs)
    if not r.ok: raise ValueError(f'{r.status_code}: {r.text[:300]}')
    return r.json()

try:
    health=get('/health')
except Exception as ex:
    st.error(f'API unavailable: {ex}')
    st.stop()

stats=get('/stats')
model=stats.get('model')
c1,c2,c3,c4=st.columns(4)
c1.metric('API status',health['status'])
c2.metric('Uptime',f"{int(health['uptime_seconds']//60)} min")
c3.metric('Prediction requests',stats['prediction_count'])
c4.metric('Average API inference',f"{stats['avg_latency_ms'] or 0} ms")
if model is None:
    st.error('No trained model is installed. Load labeled MIMII WAV data and run: python -m src.model')
    st.stop()
if model.get('synthetic_fixture'):
    st.error('SYNTHETIC SMOKE-TEST MODEL ONLY. The metrics here are not valid scientific results. Train on real MIMII recordings before submission.')

predict_tab,dash_tab,upload_tab,retrain_tab,monitor_tab=st.tabs(['🎯 Predict','📊 Dataset insights','📤 Upload training data','🔁 Retraining','📡 Monitor'])
with predict_tab:
    st.subheader('Predict from a real WAV recording')
    wav=st.file_uploader('Upload a single .wav file',type=['wav'],key='predictor')
    if wav is not None:
        st.audio(wav)
        if st.button('Predict motor condition',type='primary'):
            try:
                r=requests.post(API+'/predict',files={'file':(wav.name,wav.getvalue(),'audio/wav')},timeout=90)
                r.raise_for_status()
                p=r.json()
                st.success(f"Prediction: **{p['label'].upper()}** | Confidence: {p['confidence']:.1%}")
                st.write({'Prediction ID':p['prediction_id'],'Model version':p['model_version'],
                          'Response latency (ms)':p['latency_ms']})
                st.json(p['feature_highlights'])
                st.info('Research demonstration only. A sound prediction is not a certified mechanical diagnosis.')
            except Exception as ex: st.error(str(ex))

with dash_tab:
    st.subheader('Acoustic data insights')
    features=stats.get('feature_insights')
    if features:
        st.write('Training recordings:',features['sample_size'])
        st.bar_chart(pd.Series(features['counts']))
        for feature,detail in features['feature_stats'].items():
            st.markdown(f'**{feature}** — {features["interpretations"][feature]}')
            st.dataframe(pd.DataFrame(detail).T,use_container_width=True)
        p=Path('outputs/three_audio_features.png')
        if p.exists():st.image(str(p),caption='Three acoustic feature distributions (training data only)')
        else: st.caption('Feature distributions plot is generated by training locally.')
    else: st.info('Train a model first to generate interpretations for three acoustic features.')

with upload_tab:
    st.subheader('Upload labeled recordings for retraining')
    label=st.selectbox('Correct operating condition',options=['normal','abnormal'])
    files=st.file_uploader('Select multiple WAV files',type=['wav'],accept_multiple_files=True,key='bulk')
    if st.button('Save audio to retraining database',disabled=not bool(files)):
        try:
            payload=[('files',(f.name,f.getvalue(),'audio/wav')) for f in files]
            result=post('/upload',files=payload,data={'label':label})
            st.success(f"Stored {result['stored_count']} files in SQLite; they are pending retraining.")
        except Exception as ex: st.error(str(ex))
    st.caption('Uploaded data is added only to training, never to the held-out test set.')

with retrain_tab:
    st.subheader('Update the EXISTING trained model')
    st.write('New files waiting:',stats['pending_uploads'])
    st.write('Already incorporated:',stats['trained_uploads'])
    st.write('Current model:',model['version'])
    if st.button('Trigger model retraining',type='primary',disabled=stats['pending_uploads']==0):
        try:
            j=post('/retrain')
            st.session_state['job_id']=j['job_id']
            st.success('Retraining job created. Check the job status below.')
        except Exception as ex:st.error(str(ex))
    jid=st.text_input('Retraining job ID',value=st.session_state.get('job_id',''))
    if jid and st.button('Refresh retraining status'):
        try: st.json(get('/jobs/'+jid))
        except Exception as ex:st.error(str(ex))

with monitor_tab:
    st.subheader('Model evaluation and production performance')
    st.write('Model:',model['version'])
    st.write('Held-out test results (not production feedback)')
    test=model['test_metrics']
    st.dataframe(pd.DataFrame([{'metric':x,'value':test.get(x)} for x in
       ['accuracy','precision','recall','f1','balanced_accuracy','roc_auc','loss']]),hide_index=True)
    cm=Path('outputs/confusion_matrix.png')
    if cm.exists():st.image(str(cm),caption='Held-out test confusion matrix')
    prod=stats.get('production_feedback_metrics')
    if prod:
        st.write('Production predictions with verified ground truth:',prod)
    else:
        st.info('No production predictions have confirmed ground truth yet. Use /feedback with known labels to evaluate production predictions.')
    if stats['recent_predictions']:
        st.write('Recent inference history')
        st.dataframe(pd.DataFrame(stats['recent_predictions']),use_container_width=True)
    st.caption('Use Locust and Docker replica comparisons for actual load and latency benchmarks.')

